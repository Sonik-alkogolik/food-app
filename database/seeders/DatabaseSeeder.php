<?php

namespace Database\Seeders;

use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Cache;

/**
 * Порядок наполнения базы данных:
 * 1) категории
 * 2) базовый набор рецептов из локального каталога
 * 3) шаги к этим рецептам
 * 4) рецепты из интернета (у каждого — своё настоящее фото и видео)
 * 5) fallback-изображения (только там, где фото нет)
 * 6) структурированные ингредиенты для «Холодильника».
 * 7) администратор (логин и пароль — из ADMIN_EMAIL / ADMIN_PASSWORD).
 *
 * Порядок важен:
 * - RecipeStepSeeder идёт ДО WebRecipeSeeder, иначе он перезапишет
 *   настоящие шаги рецептов из интернета своими шаблонными.
 * - ImageUrlSeeder идёт ПОСЛЕ обоих, но пропускает записи, у которых
 *   уже есть настоящее фото, — иначе все картинки станут одинаковыми
 *   случайными.
 */
class DatabaseSeeder extends Seeder
{
    public function run(): void
    {
        $this->call([
            CategorySeeder::class,   // категории блюд
            BulkRecipeSeeder::class, // базовый набор рецептов из локального каталога
            RecipeStepSeeder::class, // шаги к базовым рецептам
            WebRecipeSeeder::class,  // реальные рецепты из интернета со своими фото
            ImageUrlSeeder::class,   // fallback-фото только там, где изображения нет
            IngredientSeeder::class, // «Холодильник»: структурированные ингредиенты
            AdminUserSeeder::class,  // администратор (логин и пароль — из .env)
        ]);

        // Сидеры пишут рецепты напрямую в БД (BulkRecipeSeeder) или через
        // upsert, поэтому события модели не срабатывают и кеш карточек
        // сам не сбросится. После наполнения базы чистим кеш целиком —
        // иначе API до часа отдаёт старые категории и устаревшие карточки.
        Cache::flush();
    }
}
