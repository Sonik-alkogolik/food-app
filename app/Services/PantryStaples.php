<?php

namespace App\Services;

/**
 * Базовые продукты — то, что есть в любой кухне.
 *
 * Правила живут здесь, а не в сидере, чтобы список можно было читать
 * в одном месте и проверять тестами. В базу флаг попадает при засеве
 * (ingredients.is_pantry_staple), и уже база — источник правды для
 * подбора рецептов.
 */
class PantryStaples
{
    /**
     * Названия базовых продуктов в нижнем регистре.
     *
     * Перечислены точно, а не «по слову»: «Перец болгарский» и
     * «Перец чили» — овощи, а не базовый продукт, и «Сахарный горошек»
     * — замороженная кукуруза, а не сахар.
     */
    public const EXACT_NAMES = [
        // Соль
        'соль',
        'соль морская',
        'морская соль',
        'соль крупного помола',
        'соль гималайская',

        // Перец (только чёрный молотый: остальные перцы — овощи)
        'перец',
        'перец чёрный',
        'перец черный',
        'перец молотый',
        'перец чёрный молотый',
        'перец черный молотый',
        'чёрный перец молотый',
        'черный перец молотый',

        // Вода
        'вода',
        'вода питьевая',
        'питьевая вода',
        'холодная вода',
        'горячая вода',
        'кипящая вода',
        'тёплая вода',
        'теплая вода',

        // Сахар
        'сахар',
        'сахар белый',
        'белый сахар',
        'сахарный песок',
        'сахар тростниковый',
        'тростниковый сахар',
        'коричневый сахар',
        'сахар коричневый',
        'сахарная пудра',
        'ванильный сахар',
        'сахар демерара',
        'сахар мусковадо',

        // Мука
        'мука',
        'мука пшеничная',
        'пшеничная мука',
        'мука быстрого приготовления',
    ];

    /**
     * Масла. Отдельное правило, потому что их названия самые разные:
     * подсолнечное, рапсовое, кунжутное, кокосовое.
     */
    public const OIL_EXCLUDE_NAMES = [
        'молотого ореха',   // масло из молотых орехов — это не staple
        'трюфельное',       // и то же
        'для формы',        // сливочное масло для формочки — часть рецепта
        'соленое',          // солёное масло — не базовый продукт
        'сладкое',          // сладкое масло — не базовый продукт
    ];

    /**
     * Базовый ли это продукт.
     */
    public function isStaple(?string $name): bool
    {
        $normalized = $this->normalize($name);

        if ($normalized === '') {
            return false;
        }

        // Название с запятой — это не один продукт, а перечисление:
        // «Зелень, соль, перец, масло» из текста рецепта. Такое нельзя
        // считать базовым: соль в нём есть, а зелень — нет.
        if (str_contains($normalized, ',')) {
            return false;
        }

        if (in_array($normalized, self::EXACT_NAMES, true)) {
            return true;
        }

        return $this->isOil($normalized);
    }

    /**
     * Масло любого вида. Исключения — в Oil_EXCLUDE_NAMES.
     *
     * Ищем слово целиком: «маслины» — это оливки, а не масло.
     */
    private function isOil(string $normalized): bool
    {
        if (!preg_match('/масл[оа]?(?=\s|$)/u', $normalized)) {
            return false;
        }

        foreach (self::OIL_EXCLUDE_NAMES as $exclude) {
            if (str_contains($normalized, $exclude)) {
                return false;
            }
        }

        return true;
    }

    /**
     * Приводит название к сравнимому виду: нижний регистр, без лишних
     * пробелов. В базе названия приходят из рецептов и отличаются
     * регистром и двойными пробелами.
     */
    public function normalize(?string $name): string
    {
        $name = mb_strtolower(trim((string) $name));
        $name = preg_replace('/\s+/u', ' ', $name);

        return trim((string) $name);
    }
}
